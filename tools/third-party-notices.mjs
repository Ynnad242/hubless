// Writes THIRD_PARTY_NOTICES.md: the license of every package bundled into Hubless, plus the data and research
// credits in docs/notices/sources.md. Run after changing dependencies: node tools/third-party-notices.mjs
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const root = new URL('..', import.meta.url).pathname
// Packages that end up in the app: the main-process dependency and everything bundled into the renderer.
const ROOTS = ['node-hid', 'electron-updater', 'react', 'react-dom', 'radix-ui', 'lucide-react', 'sonner', 'clsx', 'tailwind-merge',
  'class-variance-authority', 'tailwindcss', 'tw-animate-css']

const pkgDir = (name) => join(root, 'node_modules', name)
const seen = new Map()
function walk(name) {
  if (seen.has(name) || !existsSync(join(pkgDir(name), 'package.json'))) return
  const pkg = JSON.parse(readFileSync(join(pkgDir(name), 'package.json'), 'utf8'))
  const file = readdirSync(pkgDir(name)).find((f) => /^(licen[cs]e|copying)(\.|-|$)/i.test(f))
  seen.set(name, { name, version: pkg.version, license: pkg.license ?? 'see package', text: file ? readFileSync(join(pkgDir(name), file), 'utf8').trim() : '' })
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep)
}
ROOTS.forEach(walk)

// Packages with the same license text are listed together.
const groups = new Map()
for (const p of [...seen.values()].sort((a, b) => a.name.localeCompare(b.name))) {
  const key = p.text || `${p.license} (no license file shipped)`
  groups.set(key, [...(groups.get(key) ?? []), p])
}

let out = `# Third-party notices

Hubless is MIT licensed (see LICENSE). It is built with Electron (MIT), which ships its own Chromium and Node.js license
files (LICENSE.electron.txt and LICENSES.chromium.html next to the app). Hubless also bundles the packages below.
The node-hid package includes the hidapi C library (BSD-style license, LICENSE-bsd.txt).

Generated by tools/third-party-notices.mjs.

## Bundled packages

`
for (const [text, pkgs] of groups) {
  out += `### ${pkgs.map((p) => `${p.name} ${p.version}`).join(', ')}\n\nLicense: ${pkgs[0].license}\n\n`
  if (text && !text.endsWith('(no license file shipped)')) out += '```\n' + text + '\n```\n\n'
}
out += readFileSync(join(root, 'docs/notices/sources.md'), 'utf8')
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), out)
console.log(`${seen.size} packages in ${groups.size} license groups → THIRD_PARTY_NOTICES.md`)
